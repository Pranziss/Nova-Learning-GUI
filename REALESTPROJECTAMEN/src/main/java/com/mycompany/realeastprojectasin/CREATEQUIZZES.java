private void addQuestionPanel() {
    questionCounter++;
    
    // Create new question panel
    QuestionPanel qPanel = new QuestionPanel(questionCounter, this);
    questionPanels.add(qPanel);
    
    // Add to container with spacing
    questionsContainer.add(qPanel);
    questionsContainer.add(Box.createVerticalStrut(15));
    
    // Refresh display
    questionsContainer.revalidate();
    questionsContainer.repaint();
    
    // Auto-scroll to bottom
    SwingUtilities.invokeLater(() -> {
        JScrollBar vertical = jScrollPane1.getVerticalScrollBar();
        vertical.setValue(vertical.getMaximum());
    });
}
public void removeQuestionPanel(QuestionPanel panel) {
    if (questionPanels.size() <= 1) {
        JOptionPane.showMessageDialog(this,
            "Quiz must have at least one question!",
            "Cannot Remove",
            JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    questionPanels.remove(panel);
    questionsContainer.remove(panel);
    
    // Renumber remaining questions
    for (int i = 0; i < questionPanels.size(); i++) {
        questionPanels.get(i).setQuestionNumber(i + 1);
    }
        
    questionCounter = questionPanels.size();
    
    questionsContainer.revalidate();
    questionsContainer.repaint();
}
private void saveQuizToDatabase(String quizName, String course) {
    try {
        connection.setAutoCommit(false);
        
        // 1. Insert quiz
        String insertQuiz = "INSERT INTO quizzes (quiz_name, course, creator_id, created_at) VALUES (?, ?, ?, NOW())";
        PreparedStatement ps = connection.prepareStatement(insertQuiz, Statement.RETURN_GENERATED_KEYS);
        ps.setString(1, quizName);
        ps.setString(2, course);
        ps.setInt(3, AccountManager.getCurrentUserId());
        ps.executeUpdate();
        
        // Get generated quiz_id
        ResultSet rs = ps.getGeneratedKeys();
        int quizId = 0;
        if (rs.next()) {
            quizId = rs.getInt(1);
        }
        
        // 2. Insert all questions
        String insertQuestion = "INSERT INTO questions (quiz_id, question_text, option_a, option_b, option_c, option_d, correct_answer) VALUES (?, ?, ?, ?, ?, ?, ?)";
        PreparedStatement ps2 = connection.prepareStatement(insertQuestion);
        
        for (QuestionPanel qp : questionPanels) {
            ps2.setInt(1, quizId);
            ps2.setString(2, qp.getQuestionText());
            ps2.setString(3, qp.getOptionA());
            ps2.setString(4, qp.getOptionB());
            ps2.setString(5, qp.getOptionC());
            ps2.setString(6, qp.getOptionD());
            ps2.setString(7, qp.getCorrectAnswer());
            ps2.executeUpdate();
        }
        
        // 3. Create notification
        String insertNotif = "INSERT INTO notifications (user_id, message, type, created_at, is_read) VALUES (?, ?, ?, NOW(), false)";
        PreparedStatement ps3 = connection.prepareStatement(insertNotif);
        ps3.setInt(1, AccountManager.getCurrentUserId());
        ps3.setString(2, "You created quiz: " + quizName);
        ps3.setString(3, "quiz_created");
        ps3.executeUpdate();
        
        // Commit transaction
        connection.commit();
        connection.setAutoCommit(true);
        
        // Success message
        JOptionPane.showMessageDialog(this,
            "Quiz Created Successfully!\n\n" +
            "Quiz: " + quizName + "\n" +
            "Course: " + course + "\n" +
            "Questions: " + questionPanels.size(),
            "Success",
            JOptionPane.INFORMATION_MESSAGE);
        
        // Close window
        this.dispose();
        
    } catch (SQLException e) {
        try {
            connection.rollback();
            connection.setAutoCommit(true);
        } catch (SQLException ex) {
            ex.printStackTrace();
        }
        
        JOptionPane.showMessageDialog(this,
            "Error saving quiz:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
}
