private void removeQuestion(JButton removeButton) {
    // Confirm deletion
    int confirm = JOptionPane.showConfirmDialog(
        this,
        "Remove this question?",
        "Confirm",
        JOptionPane.YES_NO_OPTION
    );
    
    if (confirm == JOptionPane.YES_OPTION) {
        // Get the panel containing the remove button
        Container questionPanel = removeButton.getParent();
        Container container = questionPanel.getParent();
        
        // Remove it
        container.remove(questionPanel);
        container.revalidate();
        container.repaint();
        
        JOptionPane.showMessageDialog(this, "Question removed!");
    }
}
private void renumberQuestions() {
    for (int i = 0; i < questionPanels.size(); i++) {
        QuestionPanel qp = questionPanels.get(i);

        qp.setBorder(
            BorderFactory.createTitledBorder("Question " + (i + 1))
        );

        qp.repaint();
    }
}

