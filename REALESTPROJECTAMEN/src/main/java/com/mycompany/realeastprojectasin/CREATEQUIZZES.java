    private void jLabel6MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jLabel6MouseClicked
    String quizName = jTextField1.getText().trim();
    String course = jTextField2.getText().trim();
    
    // VALIDATION
    if (quizName.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Please enter a quiz name!",
            "Missing Information",
            JOptionPane.WARNING_MESSAGE);
        jTextField1.requestFocus();
        return;
    }
    
    if (course.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Please enter a course!",
            "Missing Information",
            JOptionPane.WARNING_MESSAGE);
        jTextField2.requestFocus();
        return;
    }
    
    if (questionPanels.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Please add at least one question!",
            "No Questions",
            JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    // Validate all questions are filled
    for (int i = 0; i < questionPanels.size(); i++) {
        QuestionPanel qp = questionPanels.get(i);
        if (!qp.isQuestionValid()) {
            JOptionPane.showMessageDialog(this,
                "Question " + (i + 1) + " is incomplete!\n\nPlease fill in all fields.",
                "Incomplete Question",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
    }
    
    // Save to database
    saveQuizToDatabase(quizName, course);

        this.dispose();        // TODO add your handling code here:
    }//GEN-LAST:event_jLabel6MouseClicked

