    private void loadTopStats() {
        try {
            Connection conn = DBConnection.getConnection();
            int userId = AccountManager.getCurrentUserId();
            
            // Count quizzes created
            String query1 = "SELECT COUNT(*) as total FROM quizzes WHERE creator_id = ?";
            PreparedStatement ps1 = conn.prepareStatement(query1);
            ps1.setInt(1, userId);
            ResultSet rs1 = ps1.executeQuery();
            if (rs1.next()) {
                jLabel2.setText("Quizzes Created: " + rs1.getInt("total"));
            }
            rs1.close();
            ps1.close();
            
            // Count quizzes taken
            String query2 = "SELECT COUNT(*) as total FROM responses WHERE user_id = ?";
            PreparedStatement ps2 = conn.prepareStatement(query2);
            ps2.setInt(1, userId);
            ResultSet rs2 = ps2.executeQuery();
            if (rs2.next()) {
                jLabel3.setText("Quizzes Taken: " + rs2.getInt("total"));
            }
            rs2.close();
            ps2.close();
            
            // Calculate average score
            String query3 = "SELECT AVG(score) as avg_score FROM responses WHERE user_id = ?";
            PreparedStatement ps3 = conn.prepareStatement(query3);
            ps3.setInt(1, userId);
            ResultSet rs3 = ps3.executeQuery();
            if (rs3.next()) {
                double avgScore = rs3.getDouble("avg_score");
                if (rs3.wasNull()) {
                    jLabel4.setText("Average Score: N/A");
                } else {
                    jLabel4.setText(String.format("Average Score: %.1f%%", avgScore));
                }
            }
            rs3.close();
            ps3.close();
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Error loading stats: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }
