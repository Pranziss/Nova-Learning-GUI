    private void loadQuizzesCreated() {
        try {
            Connection conn = DBConnection.getConnection();
            int userId = AccountManager.getCurrentUserId();
            
            // Query quizzes created by user
            String query = "SELECT q.quiz_name, q.course, q.created_at, " +
                          "COUNT(r.response_id) as times_taken " +
                          "FROM quizzes q " +
                          "LEFT JOIN responses r ON q.quiz_id = r.quiz_id " +
                          "WHERE q.creator_id = ? " +
                          "GROUP BY q.quiz_id, q.quiz_name, q.course, q.created_at " +
                          "ORDER BY q.created_at DESC";
            
            PreparedStatement pst = conn.prepareStatement(query);
            pst.setInt(1, userId);
            ResultSet rs = pst.executeQuery();
            
            // Create table model
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0); // Clear existing rows
            
            // Set column names
            model.setColumnIdentifiers(new String[]{"Quiz Name", "Course", "Created Date", "Times Taken"});
            
            // Check if there's data
            boolean hasData = false;
            
            // Populate table
            while (rs.next()) {
                hasData = true;
                String quizName = rs.getString("quiz_name");
                String course = rs.getString("course");
                Timestamp createdAt = rs.getTimestamp("created_at");
                int timesTaken = rs.getInt("times_taken");
                
                // Format date
                java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("MMM dd, yyyy");
                String formattedDate = sdf.format(createdAt);
                
                model.addRow(new Object[]{quizName, course, formattedDate, timesTaken});
            }
            
            if (!hasData) {
                model.addRow(new Object[]{"No quizzes created yet", "", "", ""});
            }
            
            rs.close();
            pst.close();
            
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
                "Error loading created quizzes: " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }
