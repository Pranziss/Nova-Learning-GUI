private void loadQuizzes() {
    // Clear existing
    quizzesContainer.removeAll();
    
    try {
        // Query to get all quizzes with creator info, question count, AND creator_id
        String query = 
            "SELECT q.quiz_id, q.quiz_name, q.course, u.username as creator, " +
            "q.created_at, q.creator_id, COUNT(qs.question_id) as question_count " +
            "FROM quizzes q " +
            "JOIN users u ON q.creator_id = u.user_id " +
            "LEFT JOIN questions qs ON q.quiz_id = qs.quiz_id " +
            "GROUP BY q.quiz_id " +
            "ORDER BY q.created_at DESC";
        
        Statement stmt = connection.createStatement();
        ResultSet rs = stmt.executeQuery(query);
        
        boolean hasQuizzes = false;
        while (rs.next()) {
            hasQuizzes = true;
            
            int quizId = rs.getInt("quiz_id");
            String quizName = rs.getString("quiz_name");
            String course = rs.getString("course");
            String creator = rs.getString("creator");
            String createdAt = rs.getString("created_at");
            int questionCount = rs.getInt("question_count");
            int creatorId = rs.getInt("creator_id"); // ✅ GET CREATOR ID
            
            // Create quiz card WITH creator_id
            JPanel quizCard = createQuizCard(quizId, quizName, course, creator, createdAt, questionCount, creatorId);
            
            // Add to container
            quizzesContainer.add(quizCard);
            quizzesContainer.add(Box.createVerticalStrut(15)); // Spacing between cards
        }
        
        if (!hasQuizzes) {
            JLabel noQuizLabel = new JLabel("No quizzes available yet");
            noQuizLabel.setFont(new Font("Segoe UI", Font.ITALIC, 16));
            noQuizLabel.setForeground(Color.LIGHT_GRAY);
            noQuizLabel.setAlignmentX(Component.CENTER_ALIGNMENT);
            quizzesContainer.add(noQuizLabel);
        }
        
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Error loading quizzes: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
    
    // Refresh display
    quizzesContainer.revalidate();
    quizzesContainer.repaint();
}
