// Open quiz for taking
private void openTakeQuiz(int quizId, String quizName) {
    // Check if user already took this quiz (optional warning)
    try {
        String query = "SELECT COUNT(*) as count FROM responses WHERE quiz_id = ? AND user_id = ?";
        PreparedStatement ps = connection.prepareStatement(query);
        ps.setInt(1, quizId);
        ps.setInt(2, AccountManager.getCurrentUserId());
        ResultSet rs = ps.executeQuery();
        
        if (rs.next() && rs.getInt("count") > 0) {
            int choice = JOptionPane.showConfirmDialog(this,
                "You've already taken this quiz before.\n\nTake it again?",
                "Retake Quiz",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.QUESTION_MESSAGE);
            
            if (choice != JOptionPane.YES_OPTION) return;
        }
        
    } catch (SQLException e) {
        e.printStackTrace();
    }
    
    // Open TAKEQUIZ frame
    new TAKEQUIZ(quizId, quizName).setVisible(true);
    this.dispose();
}

