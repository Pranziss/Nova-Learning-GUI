// Delete quiz
private void deleteQuiz(int quizId, String quizName) {
    // First confirmation
    int confirm = JOptionPane.showConfirmDialog(this,
        "⚠️ Delete Quiz: " + quizName + " ⚠️\n\n" +
        "This will permanently delete:\n" +
        "• All questions in this quiz\n" +
        "• All student responses\n" +
        "• All related data\n\n" +
        "This action CANNOT be undone!\n\n" +
        "Are you absolutely sure?",
        "Confirm Deletion",
        JOptionPane.YES_NO_OPTION,
        JOptionPane.WARNING_MESSAGE);
    
    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }
    
    // Second confirmation - type quiz name
    String verification = JOptionPane.showInputDialog(this,
        "Type the quiz name to confirm deletion:\n\n\"" + quizName + "\"",
        "Final Confirmation",
        JOptionPane.WARNING_MESSAGE);
    
    if (verification == null || !verification.equals(quizName)) {
        JOptionPane.showMessageDialog(this,
            "Quiz name doesn't match. Deletion cancelled.",
            "Cancelled",
            JOptionPane.INFORMATION_MESSAGE);
        return;
    }
    
    try {
        int currentUserId = AccountManager.getCurrentUserId();
        
        // Verify ownership
        String checkQuery = "SELECT creator_id FROM quizzes WHERE quiz_id = ?";
        PreparedStatement checkPst = connection.prepareStatement(checkQuery);
        checkPst.setInt(1, quizId);
        ResultSet rs = checkPst.executeQuery();
        
        if (rs.next()) {
            int creatorId = rs.getInt("creator_id");
            
            if (creatorId != currentUserId) {
                JOptionPane.showMessageDialog(this,
                    "Permission denied! You can only delete your own quizzes.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        rs.close();
        checkPst.close();
        
        // Delete quiz (CASCADE will handle related records)
        String deleteQuery = "DELETE FROM quizzes WHERE quiz_id = ?";
        PreparedStatement deletePst = connection.prepareStatement(deleteQuery);
        deletePst.setInt(1, quizId);
        
        int rowsDeleted = deletePst.executeUpdate();
        deletePst.close();
        
        if (rowsDeleted > 0) {
            // Add notification
            String notifQuery = "INSERT INTO notifications (user_id, message, type, created_at) " +
                               "VALUES (?, ?, ?, NOW())";
            PreparedStatement notifPst = connection.prepareStatement(notifQuery);
            notifPst.setInt(1, currentUserId);
            notifPst.setString(2, "You deleted quiz: " + quizName);
            notifPst.setString(3, "quiz_deleted");
            notifPst.executeUpdate();
            notifPst.close();
            
            JOptionPane.showMessageDialog(this,
                "✓ Quiz \"" + quizName + "\" deleted successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE);
            
            // Refresh quiz list
            loadQuizzes(); // Just call loadQuizzes again
        }
        
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Error deleting quiz:\n\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
        e.printStackTrace();
    }
}

