    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
      Question q = questions.get(currentIndex);
    
    // Get selected answer
    String selectedAnswer = null;
    if (jRadioButton1.isSelected()) selectedAnswer = "A";
    else if (jRadioButton2.isSelected()) selectedAnswer = "B";
    else if (jRadioButton3.isSelected()) selectedAnswer = "C";
    else if (jRadioButton4.isSelected()) selectedAnswer = "D";
    
    if (selectedAnswer == null) {
        JOptionPane.showMessageDialog(this, "Please select an answer!");
        return;
    }
    
    // Check if correct
    boolean isCorrect = selectedAnswer.equals(q.correctAnswer);
    
    if (isCorrect) {
        correctCount++;
        jLabel4.setText("✅ Correct!");
        jLabel4.setForeground(new Color(46, 204, 113)); // Green
    } else {
        jLabel4.setText("❌ Wrong! The correct answer is: " + q.correctAnswer + ")");
        jLabel4.setForeground(new Color(231, 76, 60)); // Red
    }
    
    // Show feedback
    jLabel4.setVisible(true);
    
    // Disable radios (can't change answer)
    jRadioButton1.setEnabled(false);
    jRadioButton2.setEnabled(false);
    jRadioButton3.setEnabled(false);
    jRadioButton4.setEnabled(false);
    
    // Hide Check Answer button
    jButton1.setVisible(false);
    
    // Show appropriate next button
    if (currentIndex < totalQuestions - 1) {
        jButton2.setVisible(true); // Next Question
    } else {
        jButton3.setVisible(true); // Finish Quiz
    }        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

