 private void loadQuestions() {
    try {
        String query = "SELECT * FROM questions WHERE quiz_id = ? ORDER BY question_id";
        PreparedStatement ps = connection.prepareStatement(query);
        ps.setInt(1, quizId);
        ResultSet rs = ps.executeQuery();
        
        while (rs.next()) {
            Question q = new Question();
            q.questionId = rs.getInt("question_id");
            q.questionText = rs.getString("question_text");
            q.optionA = rs.getString("option_a");
            q.optionB = rs.getString("option_b");
            q.optionC = rs.getString("option_c");
            q.optionD = rs.getString("option_d");
            q.correctAnswer = rs.getString("correct_answer");
            questions.add(q);
        }
    } catch (SQLException e) {
        e.printStackTrace();
    }
}

private void displayQuestion(int index) {
    currentIndex = index;
    Question q = questions.get(index);
    
    // Update header
    jLabel2.setText("Question " + (index + 1) + " of " + totalQuestions);
    jProgressBar1.setMaximum(totalQuestions);
    jProgressBar1.setValue(index + 1);
    jProgressBar1.setString((index + 1) + "/" + totalQuestions);
    
    // Update question and options
    jLabel3.setText("<html><body style='width:700px'><b>" + (index + 1) + ". " + q.questionText + "</b></body></html>");
    jRadioButton1.setText("<html>A) " + q.optionA + "</html>");
    jRadioButton2.setText("<html>B) " + q.optionB + "</html>");
    jRadioButton3.setText("<html>C) " + q.optionC + "</html>");
    jRadioButton4.setText("<html>D) " + q.optionD + "</html>");
    
    
    // Reset button states
    jButton1.setVisible(true); // Check Answer
    jButton1.setEnabled(false); // Disabled until answer selected
    jButton2.setVisible(false); // Next Question
    jButton3.setVisible(false); // Finish Quiz
    jLabel4.setVisible(false); // Feedback
    
    // Enable radios
    jRadioButton1.setEnabled(true);
    jRadioButton2.setEnabled(true);
    jRadioButton3.setEnabled(true);
    jRadioButton4.setEnabled(true);
    
    // Add listeners to enable Check Answer button when option selected
    addRadioListeners();
}

