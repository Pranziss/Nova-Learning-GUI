private void finishQuiz() {
    double score = (correctCount * 100.0) / totalQuestions;
    
    // Save to database
    try {
        connection.setAutoCommit(false);
        
        // Insert response
        String insertResp = "INSERT INTO responses (quiz_id, user_id, score, completed_at) VALUES (?, ?, ?, NOW())";
        PreparedStatement ps = connection.prepareStatement(insertResp, Statement.RETURN_GENERATED_KEYS);
        ps.setInt(1, quizId);
        ps.setInt(2, AccountManager.getCurrentUserId());
        ps.setDouble(3, score);
        ps.executeUpdate();
        
        // Create notification
        String insertNotif = "INSERT INTO notifications (user_id, message, type, created_at, is_read) VALUES (?, ?, ?, NOW(), false)";
        PreparedStatement ps2 = connection.prepareStatement(insertNotif);
        ps2.setInt(1, AccountManager.getCurrentUserId());
        ps2.setString(2, String.format("You scored %.0f%% on '%s'", score, quizName));
        ps2.setString(3, "quiz_taken");
        ps2.executeUpdate();
        
        connection.commit();
        connection.setAutoCommit(true);
        
        // Show final results
        String message;
        if (score >= 90) {
            message = "Excellent!";
        } else if (score >= 75) {
            message = "Great job!";
        } else if (score >= 50) {
            message = "Good effort!";
        } else {
            message = "Keep practicing!";
        }
        
        JOptionPane.showMessageDialog(this,
            String.format("Quiz Complete!\n\nYour Score: %.2f%%\n\nCorrect: %d / %d\n\n%s", 
                score, correctCount, totalQuestions, message),
            "Results",
            JOptionPane.INFORMATION_MESSAGE);
        
        // Close and go back
        dispose();
        new VIEWQUIZ().setVisible(true);
        
    } catch (SQLException e) {
        try { connection.rollback(); } catch (SQLException ex) {}
        JOptionPane.showMessageDialog(this, "Error saving results: " + e.getMessage());
        e.printStackTrace();
    }
}

