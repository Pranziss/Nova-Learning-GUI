    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
              String userMessage = jTextPane1.getText().trim();
        
        if (userMessage.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Please type a message first!",
                "Empty Message",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Display user message
        appendMessage("You", userMessage);
        jTextPane1.setText(""); // Clear input field
        
        // Show typing indicator
        appendMessage("Nova", "Typing...");
        
        // Send to Flask in background thread (so UI doesn't freeze)
        new Thread(() -> {
            try {
                String aiResponse = sendToFlask(userMessage);
                
                // Update UI on main thread
                javax.swing.SwingUtilities.invokeLater(() -> {
                    removeLastMessage(); // Remove "Typing..."
                    appendMessage("Nova", aiResponse);
                });
                
            } catch (Exception e) {
                javax.swing.SwingUtilities.invokeLater(() -> {
                    removeLastMessage();
                    appendMessage("Error", "Failed to connect: " + e.getMessage());
                    appendMessage("System", "Make sure Flask is running in VSCode!");
                });
            }
        }).start();        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

