   private void checkServerStatus() {
        try {
            URL url = new URL("http://127.0.0.1:5000/ask");
            HttpURLConnection conn = (HttpURLConnection) url.openConnection();
            conn.setRequestMethod("POST");
            conn.setConnectTimeout(2000);
            conn.disconnect();
            
            appendMessage("System", "✅ Nova is online and ready!");
        } catch (Exception e) {
            appendMessage("System", "⚠️ Warning: Cannot connect to Nova. Make sure Flask is running in VSCode!");
        }
    }
      private String sendToFlask(String message) throws Exception {
        URL url = new URL("http://127.0.0.1:5000/ask");
        HttpURLConnection conn = (HttpURLConnection) url.openConnection();
        
        // Setup request
        conn.setRequestMethod("POST");
        conn.setRequestProperty("Content-Type", "application/json");
        conn.setDoOutput(true);
        conn.setConnectTimeout(30000); // 30 second timeout
        conn.setReadTimeout(30000);
        
        // Create JSON: {"message": "user's question"}
        JSONObject payload = new JSONObject();
        payload.put("message", message);
        
        // Send request
        try (OutputStream os = conn.getOutputStream()) {
            byte[] input = payload.toString().getBytes("utf-8");
            os.write(input, 0, input.length);
        }
        
        // Read response
        int responseCode = conn.getResponseCode();
        
        if (responseCode == 200) {
            BufferedReader br = new BufferedReader(
                new InputStreamReader(conn.getInputStream(), "utf-8")
            );
            StringBuilder response = new StringBuilder();
            String line;
            while ((line = br.readLine()) != null) {
                response.append(line.trim());
            }
            br.close();
            
            // Parse JSON response: {"response": "Nova's answer"}
            JSONObject jsonResponse = new JSONObject(response.toString());
            return jsonResponse.getString("response");
        } else {
            throw new Exception("Server returned error code: " + responseCode);
        }
    }
        private void appendMessage(String sender, String message) {
        String timestamp = new java.text.SimpleDateFormat("HH:mm").format(new java.util.Date());
        String formattedMessage = String.format("[%s] %s: %s\n\n", timestamp, sender, message);
        
        txtChatDisplay.append(formattedMessage);
        
        // Auto-scroll to bottom
        txtChatDisplay.setCaretPosition(txtChatDisplay.getDocument().getLength());
    }
    
    // ========== REMOVE LAST MESSAGE (for typing indicator) ==========
    
    private void removeLastMessage() {
        String text = txtChatDisplay.getText();
        int lastIndex = text.lastIndexOf("[");
        if (lastIndex > 0) {
            txtChatDisplay.setText(text.substring(0, lastIndex));
        }
    }
